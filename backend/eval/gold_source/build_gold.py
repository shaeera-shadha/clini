def g(
    gid: str,
    section: str,
    polarity: str,
    text: str,
    evidence: list[str],
    match: Terms,
    accept: list[str] | None = None,
) -> dict[str, Any]:
    item = {
        "id": gid,
        "section": section,
        "polarity": polarity,
        "text": text,
        "evidence": evidence,
        "match": match,
    }
    if accept:
        item["accept_polarity"] = accept
    return item


def o(text: str, evidence: list[str], match: Terms) -> dict[str, Any]:
    return {"text": text, "evidence": evidence, "match": match}


def t(tid: str, description: str, match: Terms, exempt: list[str]) -> dict[str, Any]:
    return {"id": tid, "description": description, "match": match, "exempt": exempt}


